"""Render a fixed-host gateway. Never interpolates credentials or arbitrary upstream URLs."""
from pathlib import Path
from urllib.parse import urlsplit
import argparse
import re

ROUTES = {
    'portal': (8080, 'http://web:80'),
    'manyfold': (3214, 'http://manyfold:3214'),
    'mealie': (9925, 'http://mealie:9000'),
    'actual': (5006, 'http://actual:5006'),
    'opengym': (8081, 'http://opengym-web:80'),
    'octoprint': (5000, 'http://octoprint:80'),
    'homeassistant': (8123, 'http://ha-sso:8123'),
    'homeboard': (8090, 'http://homeboard:8080'),
    'cockpit': (9090, 'http://unix:/run/auroralab-cockpit/sso.sock:'),
}


def render(origin):
    parsed = urlsplit(origin)
    if parsed.scheme != 'https' or not parsed.hostname or parsed.port not in (None, 443) or parsed.path or parsed.query or parsed.fragment or parsed.username or parsed.password or not re.fullmatch(r'[a-z0-9.-]+', parsed.hostname):
        raise ValueError('Configure a origem HTTPS principal, sem caminho ou porta alternativa.')
    host = parsed.hostname
    text = '''map $http_upgrade $aurora_connection { default upgrade; '' close; }
map $http_cookie $aurora_native_cookie {
    "~^__Host-aurora_session=[^;]*(?:;\\s*)?(?<aurora_cookie_first_tail>.*)$" $aurora_cookie_first_tail;
    "~^(?<aurora_cookie_prefix>.*?);\\s*__Host-aurora_session=[^;]*(?<aurora_cookie_suffix>.*)$" "$aurora_cookie_prefix$aurora_cookie_suffix";
    default $http_cookie;
}
map "$request_method:$uri" $aurora_admin_operation {
    default 0;
    ~^POST:/api/power(?:/|$) 1;
    ~^[A-Z]+:/fitness(?:[-./]|$) 1;
}
map "$request_method:$uri" $aurora_power_operation { default 0; ~^POST:/api/power(?:/|$) 1; }
map $sso_power_key $aurora_auth_header { "" $http_authorization; default "Bearer $sso_power_key"; }
map "$request_method:$uri" $aurora_login_key { default ""; "POST:/auth/login" $binary_remote_addr; }
resolver 127.0.0.11 valid=10s ipv6=off;
proxy_headers_hash_max_size 1024;
proxy_headers_hash_bucket_size 128;
limit_req_zone $aurora_login_key zone=aurora_login:1m rate=10r/m;
'''
    # LAN HTTP exposes only a redirect. Tailscale HTTPS uses the private 18080 listener.
    text += f'server {{ listen 8088; server_name _; return 308 {origin}$request_uri; }}\n'
    for app, (port, upstream) in ROUTES.items():
        extra = ''
        if app == 'portal':
            extra = '''location = /auth/check { return 404; }
    location ^~ /auth/ {
        auth_request off;
        limit_req zone=aurora_login burst=10 nodelay;
        limit_req_status 429;
        set $auth_service http://auth:7777;
        proxy_pass $auth_service$request_uri;
        proxy_set_header Host $http_host;
        proxy_set_header X-Aurora-Client-IP $remote_addr;
        proxy_set_header X-Aurora-App "";
        proxy_set_header X-Aurora-Identity "";
        proxy_set_header X-Aurora-Proxy-Secret "";
        proxy_set_header X-Forwarded-Proto https;
        access_log off;
    }
    '''
        forwarded = '$remote_addr'
        native = ''
        authorization = '$aurora_auth_header'
        if app == 'mealie':
            native = 'proxy_set_header X-Mealie-Reverse-Proxy-Secret $sso_secret;\n        proxy_set_header X-Forwarded-User $sso_identity;'
            authorization = '""'
        if app == 'actual':
            native = 'proxy_set_header X-Actual-Password $sso_secret;'
        if app == 'homeassistant':
            forwarded = '$sso_ha_ip'
        # Identity/secret are generated by the auth subrequest, never forwarded from the client.
        text += f'''server {{
    listen {port};
    server_name {host};
    if ($host != "{host}") {{ return 421; }}
    server_tokens off;
    client_max_body_size 48m;
    access_log off;
    error_page 401 =302 {origin}/auth/;
    location = /_aurora_verify {{
        internal;
        set $auth_service http://auth:7777;
        proxy_pass $auth_service/auth/check;
        proxy_pass_request_body off;
        proxy_set_header Content-Length "";
        proxy_set_header Cookie $http_cookie;
        proxy_set_header X-Aurora-App {app};
        proxy_set_header X-Aurora-Require-Admin $required_admin;
        proxy_set_header X-Aurora-Require-Power $required_power;
        proxy_set_header X-Aurora-Method $original_method;
        proxy_set_header X-Aurora-Original-Origin $http_origin;
    }}
    {extra}location / {{
        set $original_method $request_method;
        set $required_admin $aurora_admin_operation;
        set $required_power $aurora_power_operation;
        auth_request /_aurora_verify;
        auth_request_set $sso_identity $upstream_http_x_aurora_identity;
        auth_request_set $sso_secret $upstream_http_x_aurora_app_secret;
        auth_request_set $sso_ha_ip $upstream_http_x_aurora_ha_ip;
        auth_request_set $sso_power_key $upstream_http_x_aurora_power_key;
        set $target {upstream};
        proxy_pass $target;
        proxy_http_version 1.1;
        proxy_set_header Host $http_host;
        proxy_set_header X-Forwarded-Proto https;
        proxy_set_header X-Real-IP {forwarded};
        proxy_set_header X-Forwarded-For {forwarded};
        proxy_set_header X-Aurora-Identity $sso_identity;
        proxy_set_header X-Aurora-Proxy-Secret $sso_secret;
        proxy_set_header Authorization {authorization};
        proxy_set_header Cookie $aurora_native_cookie;
        proxy_set_header Remote-User "";
        proxy_set_header X-Remote-User "";
        proxy_set_header X-Forwarded-User "";
        proxy_set_header X-Mealie-Reverse-Proxy-Secret "";
        proxy_set_header X-Actual-Password "";
        {native}
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection $aurora_connection;
        proxy_read_timeout 300s;
        proxy_buffering off;
    }}
}}
'''
    return text


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--origin', required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    text = render(args.origin.rstrip('/'))
    args.output.write_text(text, encoding='utf-8')
